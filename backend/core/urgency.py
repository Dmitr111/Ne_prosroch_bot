"""UrgencyCalculator — расчёт срочности продукта.

Переводит остаточный срок годности в вес срочности по формуле раздела 1.4:

    wᵢ = max(0, T − τᵢ)

где τᵢ — остаточный срок годности продукта в днях, T — горизонт
планирования (``horizon``). Продукт, до истечения срока которого осталось
не меньше T дней, получает нулевой вес и в подборе не участвует.

Класс без состояния: горизонт передаётся аргументом и не хранится в полях.
Весовая функция намеренно отделена от алгоритма отбора — вид wᵢ можно
менять, не трогая GreedyRecommender.
"""


class UrgencyLevel:
    """Цветовая индикация остаточного срока в интерфейсе."""

    # Срок не приближается
    GREEN = "green"
    # Срок в пределах горизонта T
    YELLOW = "yellow"
    # Истекает сегодня или уже просрочен
    RED = "red"


def urgency_level(days_left: int, horizon: int) -> str:
    """Цвет индикатора по остаточному сроку годности.

    Границы те же, что у весовой функции: продукт с ненулевым весом
    подсвечен, с нулевым — нет.
    """
    if days_left <= 0:
        return UrgencyLevel.RED
    if days_left < horizon:
        return UrgencyLevel.YELLOW
    return UrgencyLevel.GREEN


class UrgencyCalculator:
    """Весовая функция срочности."""

    @staticmethod
    def weight(days_left: int, horizon: int) -> int:
        """Вес продукта по остаточному сроку годности.

        :param days_left: остаточный срок годности в днях; отрицательное
            значение означает просрочку и даёт вес больше горизонта
        :param horizon: горизонт планирования T в днях
        :return: неотрицательный вес срочности
        """
        return max(0, horizon - days_left)

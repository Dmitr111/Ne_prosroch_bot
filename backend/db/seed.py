# ---------------------------------------------------------------------------
# Проверка данных до обращения к БД
# ---------------------------------------------------------------------------


def validate() -> None:
    """Проверяет согласованность справочников.

    Ошибка в данных должна обнаруживаться до записи в БД, а не всплывать
    нарушением внешнего ключа посреди транзакции.
    """
    status_codes = {code for code, _ in PRODUCT_STATUSES}
    if DEFAULT_STATUS_CODE not in status_codes:
        raise ValueError(
            f"статус по умолчанию {DEFAULT_STATUS_CODE!r} отсутствует "
            "в PRODUCT_STATUSES"
        )

    unknown_categories = set(INGREDIENTS) - set(CATEGORIES)
    if unknown_categories:
        raise ValueError(f"категории вне CATEGORIES: {sorted(unknown_categories)}")

    catalog: set[str] = set()
    for names in INGREDIENTS.values():
        for name in names:
            if name in catalog:
                raise ValueError(f"ингредиент {name!r} указан дважды")
            catalog.add(name)

    titles: set[str] = set()
    for recipe in RECIPES:
        if recipe.title in titles:
            raise ValueError(f"рецепт {recipe.title!r} указан дважды")
        titles.add(recipe.title)

        if not 3 <= len(recipe.ingredients) <= 6:
            raise ValueError(
                f"в рецепте {recipe.title!r} {len(recipe.ingredients)} ингредиентов, "
                "допустимо от 3 до 6"
            )

        seen: set[str] = set()
        for name, quantity, _unit in recipe.ingredients:
            if name not in catalog:
                raise ValueError(
                    f"рецепт {recipe.title!r} ссылается на ингредиент {name!r}, "
                    "которого нет в INGREDIENTS"
                )
            if name in seen:
                raise ValueError(
                    f"ингредиент {name!r} повторяется в рецепте {recipe.title!r}"
                )
            seen.add(name)
            if quantity <= 0:
                raise ValueError(
                    f"неположительное количество {name!r} в рецепте {recipe.title!r}"
                )



# Наполнение
# ---------------------------------------------------------------------------


class SeedStats(NamedTuple):
    """Сколько записей создано и сколько пропущено как уже существующие."""

    created: int
    skipped: int


async def _seed_product_statuses(session: AsyncSession) -> SeedStats:
    existing = set((await session.scalars(select(ProductStatus.code))).all())
    created = 0
    for code, name in PRODUCT_STATUSES:
        if code in existing:
            continue
        session.add(ProductStatus(code=code, name=name))
        created += 1
    await session.flush()
    return SeedStats(created, len(PRODUCT_STATUSES) - created)


async def _seed_categories(session: AsyncSession) -> SeedStats:
    existing = set((await session.scalars(select(Category.name))).all())
    created = 0
    for name in CATEGORIES:
        if name in existing:
            continue
        session.add(Category(name=name))
        created += 1
    await session.flush()
    return SeedStats(created, len(CATEGORIES) - created)


async def _seed_ingredients(session: AsyncSession) -> SeedStats:
    existing = set((await session.scalars(select(Ingredient.name))).all())
    created = 0
    total = 0
    for category_name, names in INGREDIENTS.items():
        for name in names:
            total += 1
            if name in existing:
                continue
            session.add(Ingredient(name=name, category_name=category_name))
            created += 1
    await session.flush()
    return SeedStats(created, total - created)


async def _seed_recipes(session: AsyncSession) -> SeedStats:
    existing = set((await session.scalars(select(Recipe.title))).all())
    created = 0
    for recipe in RECIPES:
        if recipe.title in existing:
            continue
        session.add(
            Recipe(
                title=recipe.title,
                description=recipe.description,
                cooking_time_min=recipe.cooking_time_min,
            )
        )
        created += 1
    await session.flush()
    return SeedStats(created, len(RECIPES) - created)


async def _seed_recipe_ingredients(session: AsyncSession) -> SeedStats:
    rows = await session.execute(
        select(RecipeIngredient.recipe_title, RecipeIngredient.ingredient_name)
    )
    existing = set(rows.all())
    created = 0
    total = 0
    for recipe in RECIPES:
        for name, quantity, unit in recipe.ingredients:
            total += 1
            if (recipe.title, name) in existing:
                continue
            session.add(
                RecipeIngredient(
                    recipe_title=recipe.title,
                    ingredient_name=name,
                    # Decimal из строки: перевод float в Numeric даёт
                    # представление вроде 0.1000000000000000055
                    quantity=Decimal(str(quantity)),
                    unit=unit,
                )
            )
            created += 1
    await session.flush()
    return SeedStats(created, total - created)


async def seed(session: AsyncSession) -> dict[str, SeedStats]:
    """Наполняет справочники в порядке зависимостей и возвращает статистику."""
    validate()
    return {
        "product_statuses": await _seed_product_statuses(session),
        "categories": await _seed_categories(session),
        "ingredients": await _seed_ingredients(session),
        "recipes": await _seed_recipes(session),
        "recipe_ingredients": await _seed_recipe_ingredients(session),
    }


def _report(stats: dict[str, SeedStats]) -> None:
    """Печатает итоги наполнения по таблицам."""
    width = max(len(table) for table in stats)
    print("Наполнение справочников:")
    for table, (created, skipped) in stats.items():
        print(f"  {table:<{width}}  создано {created:>4}, пропущено {skipped:>4}")
    total_created = sum(item.created for item in stats.values())
    total_skipped = sum(item.skipped for item in stats.values())
    print(f"Итого: создано {total_created}, пропущено {total_skipped}")


async def main() -> None:
    """Точка входа: python -m backend.db.seed."""
    try:
        async with async_session_factory() as session:
            stats = await seed(session)
            await session.commit()
        _report(stats)
    finally:
        await engine.dispose()


if __name__ == "__main__":
    asyncio.run(main())
